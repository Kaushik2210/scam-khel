const dicts: Record<Lang, Record<Key, string>> = { en, hi };

interface Ctx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: Key) => string;
}
const I18n = createContext<Ctx>({ lang: "en", setLang: () => {}, t: (k) => en[k] });

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    try {
      const saved = window.localStorage.getItem("sk_lang");
      if (saved === "hi" || saved === "en") setLangState(saved);
      else if (navigator.language?.toLowerCase().startsWith("hi")) setLangState("hi");
    } catch {
      /* default en */
    }
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      window.localStorage.setItem("sk_lang", l);
    } catch {
      /* ignore */
    }
  }, []);
  const t = useCallback((k: Key) => dicts[lang][k] ?? en[k], [lang]);
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18n.Provider value={value}>{children}</I18n.Provider>;
}

export const useI18n = () => useContext(I18n);
